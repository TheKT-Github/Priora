-- ===================================================================
-- PRIORA BASELINE SCHEMA MIGRATION (V1)
-- Portable ANSI SQL compatible with PostgreSQL 10+ and H2 (PostgreSQL Mode)
-- Foreign keys use standard RESTRICT/NO ACTION semantics matching JPA mappings
-- ===================================================================

-- 1. USERS Table (Entity: UserAccount)
CREATE TABLE USERS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(100) NOT NULL,
    ROLE VARCHAR(30) NOT NULL,
    FULL_NAME VARCHAR(100) NOT NULL,
    EMPLOYEE_NO VARCHAR(50),
    DEPARTMENT VARCHAR(100),
    CONSTRAINT uk_users_username UNIQUE (USERNAME)
);

-- 2. GRAVITY_SETTINGS Table (Entity: GravitySettings)
CREATE TABLE GRAVITY_SETTINGS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENABLE_DEPENDENCY_SCORE BOOLEAN NOT NULL DEFAULT TRUE,
    ENABLE_DEADLINE_PROXIMITY BOOLEAN NOT NULL DEFAULT TRUE,
    ENABLE_STAGNATION_SCORE BOOLEAN NOT NULL DEFAULT TRUE,
    ENABLE_WORKLOAD_DENSITY BOOLEAN NOT NULL DEFAULT TRUE,
    REQUIRE_DEV_APPROVAL BOOLEAN NOT NULL DEFAULT TRUE,
    ENABLE_CUSTOM_FACTOR BOOLEAN NOT NULL DEFAULT FALSE,
    CUSTOM_FACTOR_NAME VARCHAR(100) DEFAULT 'Custom Risk Weight',
    CUSTOM_FACTOR_POINTS DOUBLE PRECISION DEFAULT 0.0,
    VERSION BIGINT DEFAULT 0
);

-- 3. TASKS Table (Entity: Task)
CREATE TABLE TASKS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR(150) NOT NULL,
    DESCRIPTION VARCHAR(1000),
    STATUS VARCHAR(30) NOT NULL DEFAULT 'TODO',
    APPROVAL_STATUS VARCHAR(30) NOT NULL DEFAULT 'APPROVED',
    REJECTION_REASON VARCHAR(1000),
    ENVIRONMENT VARCHAR(30) NOT NULL DEFAULT 'DEVELOPMENT',
    CUSTOM_FACTOR_APPLIED BOOLEAN NOT NULL DEFAULT FALSE,
    PINGED BOOLEAN NOT NULL DEFAULT FALSE,
    ASSIGNEE_ID BIGINT,
    CREATED_BY_ID BIGINT,
    CREATED_AT TIMESTAMP NOT NULL,
    LAST_ACTIVITY_AT TIMESTAMP NOT NULL,
    DEADLINE TIMESTAMP NOT NULL,
    PING_COUNT INTEGER NOT NULL DEFAULT 0,
    VERSION BIGINT DEFAULT 0,
    CONSTRAINT fk_tasks_assignee FOREIGN KEY (ASSIGNEE_ID) REFERENCES USERS(ID),
    CONSTRAINT fk_tasks_created_by FOREIGN KEY (CREATED_BY_ID) REFERENCES USERS(ID)
);

-- 4. TASK_DEPENDENCIES Join Table (Directed Edges: Parent -> Dependent)
-- Note: Foreign keys deliberately omit ON DELETE CASCADE; task unlinking is explicitly
-- managed by TaskService.deleteTask() to preserve bidirectional referential integrity.
CREATE TABLE TASK_DEPENDENCIES (
    PARENT_TASK_ID BIGINT NOT NULL,
    DEPENDENT_TASK_ID BIGINT NOT NULL,
    CONSTRAINT pk_task_dependencies PRIMARY KEY (PARENT_TASK_ID, DEPENDENT_TASK_ID),
    CONSTRAINT fk_task_deps_parent FOREIGN KEY (PARENT_TASK_ID) REFERENCES TASKS(ID),
    CONSTRAINT fk_task_deps_dependent FOREIGN KEY (DEPENDENT_TASK_ID) REFERENCES TASKS(ID)
);
